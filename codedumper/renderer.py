"""Markdown serialization and dynamic code block fencing for CodeDumper."""

import re
from codedumper.models import ScanConfig, ScanResult


def calculate_code_fence(content: str) -> str:
    """Calculate the minimum code fence length required to safely wrap content.

    Finds the maximum sequence of consecutive backticks in content and returns
    a fence string with at least max(3, max_backticks + 1) backticks.
    """
    matches = re.findall(r"`+", content)
    if not matches:
        return "```"
    max_backticks = max(len(m) for m in matches)
    return "`" * max(3, max_backticks + 1)


def format_size(size_bytes: int) -> str:
    """Format bytes into human-readable size string."""
    if size_bytes < 1024:
        return f"{size_bytes} B"
    elif size_bytes < 1024 * 1024:
        return f"{size_bytes / 1024:.1f} KB"
    else:
        return f"{size_bytes / (1024 * 1024):.2f} MB"


def render_markdown(config: ScanConfig, result: ScanResult) -> str:
    """Render the complete repository scan result into a single Markdown document."""
    parts = []

    # Title & Metadata
    parts.append(f"# Codebase Dump: {result.project_name}\n")
    parts.append("> *Generated by [CodeDumper](https://github.com/farhadakhtar/code_dumper)*\n")

    parts.append("## Overview\n")
    parts.append("| Metric | Value |")
    parts.append("|---|---|")
    parts.append(f"| **Target Directory** | `{result.target_dir.as_posix()}` |")
    parts.append(f"| **Files Dumped** | {len(result.included_files)} |")
    parts.append(f"| **Total Source Size** | {format_size(result.total_included_bytes)} |")
    parts.append(f"| **Total Lines** | {result.total_lines:,} |")
    parts.append(f"| **Files Omitted** | {len(result.omitted_files)} |")
    parts.append(f"| **Scan Duration** | {result.elapsed_seconds:.2f} seconds |\n")

    # Table of Contents
    if result.included_files:
        parts.append("## Table of Contents\n")
        for item in result.included_files:
            # Anchor slug
            slug = item.rel_path.replace("/", "-").replace(".", "-").replace("_", "-").lower()
            parts.append(f"- [{item.rel_path}](#file-{slug})")
        parts.append("")

    # Directory Tree
    if result.tree_text:
        parts.append("## Directory Tree\n")
        parts.append("```text")
        parts.append(result.tree_text)
        parts.append("```\n")

    # File Contents
    if result.included_files:
        parts.append("## Repository Files\n")
        for item in result.included_files:
            slug = item.rel_path.replace("/", "-").replace(".", "-").replace("_", "-").lower()
            parts.append(f'<a id="file-{slug}"></a>')
            parts.append(f"### File: `{item.rel_path}`\n")
            parts.append(f"- **Language:** `{item.language}` | **Size:** {format_size(item.size)} | **Lines:** {item.line_count}\n")

            fence = calculate_code_fence(item.content)
            parts.append(f"{fence}{item.language}")
            parts.append(item.content)
            parts.append(f"{fence}\n")

    # Omission Manifest
    if result.omitted_files:
        parts.append("## Omission Manifest\n")
        parts.append("The following files and paths were discovered during scanning but excluded from the dump:\n")
        parts.append("| Relative Path | Reason | File Size |")
        parts.append("|---|---|---|")
        for omitted in result.omitted_files:
            size_str = format_size(omitted.size) if omitted.size > 0 else "-"
            parts.append(f"| `{omitted.rel_path}` | {omitted.reason} | {size_str} |")
        parts.append("")

    return "\n".join(parts)
